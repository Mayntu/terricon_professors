import { expect, test } from '@playwright/test'
import { API, loginAs, noOverflow, resetDemo, shot } from './helpers'

test.beforeEach(async ({ page }) => { await resetDemo(page) })

test('руководитель: своя команда видна, чужой сотрудник недоступен — в UI, по прямому URL и через API', async ({ page }) => {
  await loginAs(page, 'erlan', '/manager/team')
  const people = page.getByTestId('people')
  await expect(people).toContainText('Айгерим Сейткали')
  await expect(people).toContainText('Нурлан Абенов')
  await expect(people).not.toContainText('Асель')
  await expect(people).not.toContainText('₸')
  await shot(page, 'manager-team-1440')
  await people.getByRole('link', { name: 'Айгерим Сейткали' }).click()
  const profile = page.getByTestId('employee-profile')
  await expect(profile).toContainText('СЦ Алматы · смена Б')
  await expect(profile).toContainText('Ерлан Мухамедов')
  await expect(profile).not.toContainText('Оклад')
  await shot(page, 'manager-employee-1440')
  await page.goto('/employees/emp-asel')
  await expect(page.getByTestId('employee-forbidden')).toContainText('не из вашей команды')
  await expect(page.locator('body')).not.toContainText('Касымова')
  await shot(page, 'manager-employee-403-1440')
  const { accessToken } = await (await page.request.post(`${API}/api/demo/login-as`, { data: { login: 'erlan' } })).json()
  const r = await page.request.get(`${API}/api/employees/emp-asel`, { headers: { Authorization: `Bearer ${accessToken}` } })
  expect(r.status()).toBe(403)
  expect(await r.text()).not.toContain('Касымова')
})

test('HR: все сотрудники с окладом, фильтр KG, профиль', async ({ page }) => {
  await loginAs(page, 'daniyar', '/hr/employees')
  const people = page.getByTestId('people')
  await expect(people.locator('li')).toHaveCount(8)
  await expect(people.locator('li[data-employee="emp-aigerim"]')).toContainText('240 000 ₸')
  await shot(page, 'hr-employees-1440')
  await page.getByRole('radio', { name: 'KG' }).check({ force: true })
  await expect(people.locator('li')).toHaveCount(2)
  await page.getByRole('radio', { name: 'Все страны' }).check({ force: true })
  await page.getByPlaceholder('Поиск по имени').fill('асель')
  await expect(people.locator('li')).toHaveCount(1)
  await people.getByRole('link', { name: 'Асель Касымова' }).click()
  await expect(page.getByTestId('employee-profile')).toContainText('смена А')
})

test('HR: реестр заявок — фильтры, анонимное обращение без автора, карточка с историей', async ({ page }) => {
  const a = await (await page.request.post(`${API}/api/demo/login-as`, { data: { login: 'aigerim' } })).json()
  await page.request.post(`${API}/api/ext/grievances`, { headers: { Authorization: `Bearer ${a.accessToken}` }, data: { category: 'safety', text: 'Скользкий пол у ворот 3', anonymous: true } })
  await loginAs(page, 'daniyar', '/hr/requests')
  const reg = page.getByTestId('registry')
  await expect(reg.locator('li').first()).toBeVisible()
  await shot(page, 'hr-requests-1440')
  await page.getByLabel('Тип').selectOption('grievance')
  await expect(reg.locator('li')).toHaveCount(1)
  await expect(reg.getByTestId('author')).toHaveText('Анонимно')
  await reg.getByRole('link').first().click()
  await expect(page.getByTestId('hr-request')).toContainText('Скользкий пол')
  await expect(page.locator('body')).not.toContainText('Айгерим')
  await page.goto('/hr/requests')
  await page.getByLabel('Тип').selectOption('vacation')
  await page.getByLabel('Статус').selectOption('Rejected')
  await expect(reg.locator('li')).toHaveCount(2)
  await reg.getByRole('link').first().click()
  await expect(page.locator('.request-history li')).not.toHaveCount(0)
  await shot(page, 'hr-request-card-1440')
})

for (const [login, path, name] of [['erlan', '/manager/team', 'manager-team-375'], ['daniyar', '/hr/employees', 'hr-employees-375'], ['daniyar', '/hr/requests', 'hr-requests-375']] as const) {
  test(name, async ({ page }) => {
    await page.setViewportSize({ width: 375, height: 812 })
    await loginAs(page, login, path)
    await expect(page.locator('.ext-list').first()).toBeVisible()
    await noOverflow(page)
    await shot(page, name)
  })
}
